#!/usr/bin/env python3
"""Phase 1.1: every stage (in play order) and every rule of the four MSX games.

Merges the private evidence (`stage_map.json`, `rules.json` per game: spawns decoded
from the ROM tables, events, music, graphics, bosses, routes, secrets; weapon systems,
lives, two players, loops) into a public summary. The full spawn tables (positions,
timings) are level data from the ROMs and stay in the private evidence; the public file
keeps how many of each object a stage spawns, the events, bosses, music, routes, secrets
and the rules.

    python tools/stages_msx.py --evidence /path/to/evidence
Outputs: manifests/stages_msx.json, docs/STAGES_AND_RULES.md.
"""
from __future__ import annotations
import argparse, collections, datetime, json, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parents[1]
GAMES = [('nemesis', 'Nemesis'), ('nemesis2', 'Nemesis 2'), ('salamander', 'Salamander'), ('nemesis3', 'Nemesis 3')]

def text(v, n=None):
    if v is None: return '-'
    if isinstance(v, (list, tuple)): s = '; '.join(text(x) for x in v)
    elif isinstance(v, dict):
        s = ', '.join('%s: %s' % (k, text(x)) for k, x in v.items() if not isinstance(x, (dict, list)) or len(json.dumps(x)) < 200)
    else: s = str(v)
    s = s.replace('|', '/').replace('\n', ' ')
    return s if n is None or len(s) <= n else s[:n - 1] + '...'

def spawn_summary(spawns):
    c = collections.Counter()
    if isinstance(spawns, str): return {'(%s)' % spawns: 0}   # e.g. a return visit: "same as <stage>"
    for sp in spawns or []:
        if not isinstance(sp, dict): continue
        obj = sp.get('object') or sp.get('type') or '?'
        try: n = int(sp.get('count') or 1)
        except (TypeError, ValueError): n = 1
        c[obj] += n
    return dict(sorted(c.items()))

def public_stage(st):
    out = {k: st.get(k) for k in ('id', 'order', 'name', 'map_id', 'reached_from', 'leads_to', 'subbosses',
                                  'secrets', 'hazards', 'notes') if st.get(k) not in (None, '', [])}
    sc = st.get('scroll') or {}
    if isinstance(sc, dict):
        out['scroll'] = {k: sc.get(k) for k in ('direction', 'speed', 'length', 'mid_stage_changes') if sc.get(k) is not None}
    out['music'] = st.get('music') or []
    out['graphics'] = st.get('graphics') or {}
    out['spawn_entries'] = len(st['spawns']) if isinstance(st.get('spawns'), list) else 0
    out['spawns_by_object'] = spawn_summary(st.get('spawns'))
    out['events'] = [{k: e.get(k) for k in ('at', 'what', 'source') if e.get(k) is not None} if isinstance(e, dict) else e
                     for e in st.get('events') or []]
    out['boss'] = st.get('boss')
    return out

def build(evidence):
    cat = dict(schema=1, generated=datetime.date.today().isoformat(), games={})
    for game, title in GAMES:
        sm, rl = evidence / game / 'stage_map.json', evidence / game / 'rules.json'
        if not sm.is_file():
            cat['games'][game] = dict(title=title, status='pending'); continue
        stages = json.loads(sm.read_text())
        if isinstance(stages, dict): stages = stages.get('stages', [])
        rules = json.loads(rl.read_text()) if rl.is_file() else {}
        pub = [public_stage(s) for s in stages]
        cat['games'][game] = dict(title=title, status='mapped', stages=pub, rules=rules,
                                  counts=dict(stages=len(pub), spawn_entries=sum(s['spawn_entries'] for s in pub),
                                              events=sum(len(s['events']) for s in pub),
                                              secrets=len(rules.get('secrets') or [])))
    return cat

def markdown(cat):
    L = ['# Stages and rules of the four MSX games (Phase 1.1) - generated by tools/stages_msx.py; do not edit', '',
         'Every stage in the order a player meets it (branches, return trips, boss interiors, bonus and secret',
         'stages included), decoded from the code and checked in openMSX runs, and the rules of each game.',
         'The full spawn tables (positions and timings) stay in the private evidence; here each stage lists how',
         'many of each object it spawns. Object ids refer to docs/CATALOG_MSX.md, music codes to docs/CATALOG_MUSIC.md.', '',
         '| game | stages / visits | spawn entries | events | secrets |', '|---|---|---|---|---|']
    for g in cat['games'].values():
        c = g.get('counts')
        L.append('| %s | %s | %s | %s | %s |' % ((g['title'],) + ((c['stages'], c['spawn_entries'], c['events'], c['secrets']) if c else (g['status'], '', '', ''))))
    for g in cat['games'].values():
        if not g.get('stages'): continue
        L += ['', '## %s' % g['title'], '', '### Play order', '',
              '| # | stage | scroll | music | boss | leads to | spawns |', '|---|---|---|---|---|---|---|']
        for s in g['stages']:
            boss = s.get('boss'); boss = boss.get('object') if isinstance(boss, dict) else boss
            mus = ', '.join(str(m.get('code')) if isinstance(m, dict) else str(m) for m in s['music'])
            lead = '; '.join('%s (%s)' % (x.get('to'), x.get('condition')) if isinstance(x, dict) else str(x) for x in s.get('leads_to') or [])
            L.append('| %s | %s | %s | %s | %s | %s | %d |' % (s.get('order'), text(s.get('name'), 60), text((s.get('scroll') or {}).get('direction')),
                     text(mus, 40), text(boss, 40), text(lead, 120), s['spawn_entries']))
        for s in g['stages']:
            L += ['', '#### %s. %s' % (s.get('order'), text(s.get('name')))]
            if s['spawns_by_object']:
                L.append('Spawns: ' + ', '.join(('%s x%d' % kv) if kv[1] else kv[0] for kv in s['spawns_by_object'].items()) + '.')
            for e in s['events'][:40]:
                L.append('- event: %s' % (text(e) if not isinstance(e, dict) else '%s at %s' % (text(e.get('what')), text(e.get('at')))))
            for x in s.get('secrets') or []:
                L.append('- secret: %s' % text(x, 400))
            if isinstance(s.get('boss'), dict):
                L.append('- boss: %s' % text(s['boss'], 400))
        r = g.get('rules') or {}
        if r:
            L += ['', '### Rules', '']
            for k in ('weapon_system', 'player', 'scoring', 'difficulty', 'special_stage_rules', 'secrets', 'attract_and_menus'):
                if r.get(k) is None: continue
                L += ['#### %s' % k.replace('_', ' '), '', '```json', json.dumps(r[k], indent=1, ensure_ascii=False)[:6000], '```', '']
    return '\n'.join(L) + '\n'

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--evidence', type=pathlib.Path, required=True)
    a = ap.parse_args()
    cat = build(a.evidence)
    (ROOT / 'manifests/stages_msx.json').write_text(json.dumps(cat, indent=1, ensure_ascii=False) + '\n')
    (ROOT / 'docs/STAGES_AND_RULES.md').write_text(markdown(cat))
    for g in cat['games'].values(): print(g['title'], json.dumps(g.get('counts', g['status'])))
    return 0

if __name__ == '__main__':
    sys.exit(main())
