#!/usr/bin/env python3
"""Phase 3: the registry of Nemesis Legends assets (consistency across the four chapters).

Owner's rule (docs/DECISIONS.md): an enemy, sub-boss, boss, stage element, music or any other
asset that appears in more than one place in the MSX games is the same asset everywhere in
Legends; the visual is shared, the behaviour stays the original behaviour of each game.

The private evidence (`consistency/legends_assets.json`) groups every catalogued MSX object,
screen, stage tile set and music code into Legends assets: one visual each (an NES object, the
owner's Salamander FC ship, or an MSX drawing to convert), the members with their game,
phase-2 decision and behaviour reference, and why they were merged (same NES choice, same
MSX pixels, same series object). This tool validates it and publishes it without graphics.

    python tools/legends_assets.py --evidence /path/to/evidence
Outputs: manifests/legends_assets.json, docs/LEGENDS_ASSETS.md.
"""
from __future__ import annotations
import argparse, collections, json, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parents[1]
GT = {'nemesis': 'N1', 'nemesis2': 'N2', 'salamander': 'SAL', 'nemesis3': 'N3'}

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--evidence', type=pathlib.Path, required=True)
    a = ap.parse_args()
    d = json.loads((a.evidence / 'consistency/legends_assets.json').read_text())
    A = d['assets']; problems = list(d.get('problems') or [])
    ids = collections.Counter(x['id'] for x in A)
    problems += ['duplicate asset id %s' % i for i, n in ids.items() if n > 1]
    seen = collections.Counter()
    for x in A:
        for m in x.get('members') or []:
            key = m.get('msx_id') or '%s:%s' % (m.get('msx_game') or m.get('game'), m.get('msx_code') or m.get('code'))
            seen[key] += 1
    problems += ['member in more than one asset: %s' % k for k, n in seen.items() if n > 1]
    out = dict(schema=1, rule='docs/DECISIONS.md phase 3', generated_by='tools/legends_assets.py', counts=d.get('counts'),
               not_needed_excluded=d.get('not_needed_excluded'), problems=problems, assets=A)
    (ROOT / 'manifests/legends_assets.json').write_text(json.dumps(out, indent=1, ensure_ascii=False) + '\n')
    c = d.get('counts') or {}
    L = ['# Nemesis Legends asset registry (Phase 3) - generated by tools/legends_assets.py; do not edit', '',
         'Everything the four MSX games show or play, grouped into Legends assets: one visual (or one tune)',
         'per asset, shared by every MSX object that is the same thing, each member keeping its own game\'s',
         'behaviour. Visual kinds: NES = an NES object chosen in phase 2 (REUSE as is, ADAPT with added frames',
         'or states); MSX_CONVERT = no NES version, the MSX drawing is converted in phase 5; OWNER_SHIP =',
         'the Salamander (Famicom) ships. Music sources: the NES version when one exists, otherwise the MSX tune.', '',
         '| | count |', '|---|---|']
    for k in ('assets_total', 'object_and_screen_assets', 'object_and_screen_members', 'merged_across_games', 'stage_tileset_assets',
              'stage_tileset_across_games', 'music_assets', 'music_members', 'music_across_games'):
        if k in c: L.append('| %s | %s |' % (k.replace('_', ' '), c[k]))
    vis = collections.Counter((x.get('visual') or {}).get('kind') for x in A)
    L += ['', 'Visual kinds: ' + ', '.join('%s %d' % kv for kv in vis.most_common()) + '.']
    order = ['player', 'player_weapon', 'powerup', 'item', 'hud', 'enemy', 'subboss', 'boss', 'boss_part', 'projectile', 'effect',
             'scenery', 'screen', 'stage_tileset', 'music']
    by = collections.defaultdict(list)
    for x in A: by[x.get('role')].append(x)
    for role in order + sorted(set(by) - set(order)):
        if not by.get(role): continue
        L += ['', '## %s (%d)' % (role, len(by[role])), '', '| id | name | visual | work | members |', '|---|---|---|---|---|']
        for x in sorted(by[role], key=lambda x: x['id']):
            v = x.get('visual') or {}
            src = v.get('source')
            if isinstance(src, dict): src = '%s %s %s' % (src.get('kind') or '', src.get('game') or '', src.get('code') or '')
            mem = collections.Counter(GT.get(m.get('game') or m.get('msx_game'), '?') for m in x.get('members') or [])
            L.append('| %s | %s | %s %s | %s | %s |' % (x['id'], (x.get('name') or '').replace('|', '/'), v.get('kind') or '', src or '',
                     v.get('work') or '-', ', '.join('%s %d' % kv for kv in sorted(mem.items()))))
    if problems: L += ['', '## Problems', ''] + ['- ' + p for p in problems]
    (ROOT / 'docs/LEGENDS_ASSETS.md').write_text('\n'.join(L) + '\n')
    print(len(A), 'assets;', dict(vis), 'problems:', len(problems))
    return 1 if problems else 0

if __name__ == '__main__':
    sys.exit(main())
