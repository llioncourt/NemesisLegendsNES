#!/usr/bin/env python3
"""Phase 1c: music and sound catalogue of the ten source ROMs (docs/DECISIONS.md).

Every source game sends all its music, jingles and sound effects through one request
routine. The private evidence of each game logs that routine in emulator runs that
cover every stage, boss, secret route, screen and ending, and runs every code through
the game's own sound driver for loops and chips. This tool merges those logs into a
public catalogue (codes, names, where each one plays, loops, chips, code references;
no audio and no ROM bytes).

    python tools/catalog_music.py --evidence /path/to/evidence
Outputs: manifests/catalog_music.json, docs/CATALOG_MUSIC.md.
"""
from __future__ import annotations
import argparse, collections, datetime, json, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parents[1]
GAMES = [('nemesis', 'Nemesis (MSX)'), ('nemesis2', 'Nemesis 2 (MSX)'), ('salamander', 'Salamander (MSX)'),
         ('nemesis3', 'Nemesis 3 (MSX)'), ('gradius_nes', 'Gradius (NES US/JP)'), ('gradius2_fc', 'Gradius II (Famicom)'),
         ('lifeforce_nes', 'Life Force (NES US/Rev 1)'), ('salamander_fc', 'Salamander (Famicom)')]
KEEP = ('code', 'kind', 'name', 'used_in', 'loops', 'chips', 'requested_by', 'part_of', 'never_requested', 'notes',
        'published_title', 'length_s', 'loop_s')

def entries(doc):
    if isinstance(doc, list): return doc
    for k in ('sounds', 'entries', 'codes', 'tracks'):
        if isinstance(doc.get(k), list): return doc[k]
    return []

def requested(e):
    if e.get('never_requested') is True: return False
    if e.get('requested') is False: return False
    if e.get('requests_logged') == 0: return False
    return bool(e.get('used_in')) or e.get('requested') is True or bool(e.get('requests_logged'))

def build(evidence):
    cat = dict(schema=1, generated=datetime.date.today().isoformat(), method='docs/CATALOG_METHOD.md', games={})
    for game, title in GAMES:
        p = evidence / game / 'music.json'
        if not p.is_file():
            cat['games'][game] = dict(title=title, status='pending'); continue
        doc = json.loads(p.read_text()); rows = []
        for e in entries(doc):
            r = {k: e.get(k) for k in KEEP if e.get(k) not in (None, [], '')}
            r['requested_in_runs'] = requested(e)
            if r.get('part_of'): r['kind'] = 'part'   # extra channel of a multi-channel tune
            rows.append(r)
        kinds = collections.Counter(r.get('kind') or 'none' for r in rows)
        cat['games'][game] = dict(title=title, status='catalogued', sounds=rows,
                                  counts=dict(codes=len(rows), by_kind=dict(sorted(kinds.items())),
                                              requested=sum(r['requested_in_runs'] for r in rows)))
    return cat

def cell(v):
    if isinstance(v, list): v = '; '.join(str(x) for x in v[:6]) + (' (+%d)' % (len(v) - 6) if len(v) > 6 else '')
    return ('-' if v in (None, '') else str(v)).replace('|', '/').replace('\n', ' ')

def markdown(cat):
    L = ['# Music and sound catalogue (Phase 1c) - generated by tools/catalog_music.py; do not edit', '',
         'Every request of every source game, logged at the game\'s own sound-request routine during emulator',
         'runs of every stage, boss, secret route, screen and ending. "Code" is the request number the game',
         'uses. Multi-channel tunes may own several consecutive codes (`part_of`). No audio here: the private',
         'evidence and the rips hold the sound.', '', '## Totals', '',
         '| game | codes | music | jingles | effects | requested in the runs |', '|---|---|---|---|---|---|']
    for g in cat['games'].values():
        c = g.get('counts')
        if not c: L.append('| %s | %s | | | | |' % (g['title'], g['status'])); continue
        k = c['by_kind']
        L.append('| %s | %d | %d | %d | %d | %d |' % (g['title'], c['codes'], k.get('music', 0), k.get('jingle', 0),
                                                     k.get('sfx', 0), c['requested']))
    for g in cat['games'].values():
        if not g.get('sounds'): continue
        L += ['', '## %s' % g['title'], '', '### Music and jingles', '',
              '| code | kind | name | plays in | loops | chips | requested by |', '|---|---|---|---|---|---|---|']
        for r in g['sounds']:
            if r.get('kind') in ('music', 'jingle'):
                L.append('| %s | %s | %s | %s | %s | %s | %s |' % (r['code'], r['kind'], cell(r.get('name')), cell(r.get('used_in')),
                         cell(r.get('loops')), cell(r.get('chips')), cell(r.get('requested_by'))))
        sfx = [r for r in g['sounds'] if r.get('kind') == 'sfx']
        if sfx:
            L += ['', '### Sound effects (%d)' % len(sfx), '', '| code | name | heard in | requested by |', '|---|---|---|---|']
            for r in sfx:
                L.append('| %s | %s | %s | %s |' % (r['code'], cell(r.get('name')), cell(r.get('used_in')), cell(r.get('requested_by'))))
        other = [r for r in g['sounds'] if r.get('kind') not in ('music', 'jingle', 'sfx')]
        if other:
            L += ['', 'Other codes (silence, driver commands, channel parts, empty slots): ' +
                  ', '.join('%s %s%s' % (r['code'], r.get('kind') or 'none', ' of ' + str(r['part_of']) if r.get('part_of') else '') for r in other)]
    return '\n'.join(L) + '\n'

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--evidence', type=pathlib.Path, required=True)
    a = ap.parse_args()
    cat = build(a.evidence)
    (ROOT / 'manifests/catalog_music.json').write_text(json.dumps(cat, indent=1, ensure_ascii=False) + '\n')
    (ROOT / 'docs/CATALOG_MUSIC.md').write_text(markdown(cat))
    for g in cat['games'].values(): print(g['title'], json.dumps(g.get('counts', g['status'])))
    return 0

if __name__ == '__main__':
    sys.exit(main())
