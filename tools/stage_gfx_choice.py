#!/usr/bin/env python3
"""Phase 2b: the graphics each MSX stage will be drawn with on the NES.

The map layout of every stage stays the MSX one; this table chooses the tiles, palettes and
background objects (owner's phase 2 rules: the NES version when one exists, any NES game; the
most detailed when several do; Gradius II on equal detail). Merges the private per-game
evidence (`stage_gfx_match.json`, side-by-side stage strips) into a public table.

    python tools/stage_gfx_choice.py --evidence /path/to/evidence
Outputs: manifests/stage_gfx_choice.json, docs/STAGE_GFX_CHOICE.md.
"""
from __future__ import annotations
import argparse, collections, datetime, json, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parents[1]
GAMES = [('nemesis', 'Nemesis'), ('nemesis2', 'Nemesis 2'), ('salamander', 'Salamander'), ('nemesis3', 'Nemesis 3')]
NT = {'gradius_nes': 'Gradius', 'gradius2_fc': 'Gradius II', 'lifeforce_nes': 'Life Force', 'salamander_fc': 'Salamander FC'}
DECISIONS = ['REUSE_NES_TILESET', 'ADAPT_NES_TILESET', 'CONVERT_MSX']

def build(evidence):
    out = dict(schema=1, generated=datetime.date.today().isoformat(), games={})
    for game, title in GAMES:
        p = evidence / game / 'stage_gfx_match.json'
        if not p.is_file():
            out['games'][game] = dict(title=title, status='pending'); continue
        d = json.loads(p.read_text()); L = d if isinstance(d, list) else d.get('entries') or d.get('stages') or []
        rows = []
        for e in L:
            ch = e.get('chosen') or None
            rows.append(dict(stage_id=e.get('stage_id'), name=e.get('name') or e.get('stage_name'), theme=e.get('theme'),
                             same_as=e.get('same_as'), decision=e.get('decision'),
                             chosen=({k: ch.get(k) for k in ('nes_game', 'nes_stage', 'nes_stage_name', 'tile_source') if ch.get(k) is not None}
                                     if isinstance(ch, dict) else ch),
                             why_chosen=e.get('why_chosen'), missing=e.get('missing'), confidence=e.get('confidence'),
                             candidates=[{k: c.get(k) for k in ('nes_game', 'nes_stage', 'verdict', 'evidence')} for c in e.get('candidates') or []],
                             elements=[{k: x.get(k) for k in ('msx', 'nes', 'decision')} if isinstance(x, dict) else x for x in e.get('elements') or []]))
        dec = collections.Counter(r['decision'] for r in rows)
        src = collections.Counter('%s stage %s' % (NT.get(r['chosen'].get('nes_game'), r['chosen'].get('nes_game')), r['chosen'].get('nes_stage'))
                                  for r in rows if isinstance(r['chosen'], dict) and r['chosen'].get('nes_game') and not r['same_as'])
        out['games'][game] = dict(title=title, status='compared', stages=rows,
                                  counts=dict(records=len(rows), by_decision={k: dec.get(k, 0) for k in DECISIONS},
                                              nes_sources=dict(src.most_common())))
    return out

def cell(v, n=200):
    if isinstance(v, dict): v = '%s stage %s' % (NT.get(v.get('nes_game'), v.get('nes_game')), v.get('nes_stage'))
    s = ('-' if v in (None, '') else str(v)).replace('|', '/').replace('\n', ' ')
    return s if len(s) <= n else s[:n - 1] + '...'

def markdown(c):
    L = ['# Stage graphics choice (Phase 2b) - generated by tools/stage_gfx_choice.py; do not edit', '',
         'For every stage of the MSX games: the NES stage whose graphics (tiles, palettes, background objects)',
         'will draw it. The layout stays the MSX one. REUSE_NES_TILESET = the NES set covers the stage;',
         'ADAPT_NES_TILESET = NES set plus re-cut or new pieces; CONVERT_MSX = no NES stage with that theme.',
         'Side-by-side stage strips are in the private evidence.', '',
         '| game | records | reuse | adapt | convert | NES sources |', '|---|---|---|---|---|---|']
    for g in c['games'].values():
        k = g.get('counts')
        if not k: L.append('| %s | %s | | | | |' % (g['title'], g['status'])); continue
        b = k['by_decision']
        L.append('| %s | %d | %d | %d | %d | %s |' % (g['title'], k['records'], b['REUSE_NES_TILESET'], b['ADAPT_NES_TILESET'], b['CONVERT_MSX'],
                 ', '.join('%s (%d)' % kv for kv in k['nes_sources'].items())))
    for g in c['games'].values():
        if not g.get('stages'): continue
        L += ['', '## %s' % g['title'], '', '| stage | theme | decision | NES graphics | why | to draw new | confidence |', '|---|---|---|---|---|---|---|']
        for r in g['stages']:
            if r['same_as']:
                L.append('| %s | (same as %s) | %s | %s | | | |' % (r['stage_id'], r['same_as'], r['decision'] or '-', cell(r['chosen'])))
                continue
            L.append('| %s | %s | %s | %s | %s | %s | %s |' % (r['stage_id'], cell(r['theme'], 90), r['decision'], cell(r['chosen']),
                     cell(r['why_chosen'], 220), cell(r['missing'], 200), r['confidence'] or '-'))
    return '\n'.join(L) + '\n'

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--evidence', type=pathlib.Path, required=True)
    a = ap.parse_args()
    c = build(a.evidence)
    (ROOT / 'manifests/stage_gfx_choice.json').write_text(json.dumps(c, indent=1, ensure_ascii=False) + '\n')
    (ROOT / 'docs/STAGE_GFX_CHOICE.md').write_text(markdown(c))
    for g in c['games'].values(): print(g['title'], json.dumps(g.get('counts', g['status']), ensure_ascii=False))
    return 0

if __name__ == '__main__':
    sys.exit(main())
