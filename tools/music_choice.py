#!/usr/bin/env python3
"""Phase 2c: which MSX music and jingles already exist on the NES (same composition).

Owner's rule (docs/DECISIONS.md): when the same music exists in a NES game, Legends uses the
NES version; otherwise the MSX music is converted later in two arrangements (plain APU and
MMC5). The private evidence (`music_match/music_match.json`) compares the note sequences of
every MSX tune (read from each game's own sound driver) with every NES tune of Gradius,
Gradius II, Life Force and Salamander (Famicom), transposition-invariant, and chooses the most
complete NES arrangement (Gradius II on a tie). This tool publishes the decisions.

    python tools/music_choice.py --evidence /path/to/evidence
Outputs: manifests/music_choice.json, docs/MUSIC_CHOICE.md.
"""
from __future__ import annotations
import argparse, collections, datetime, json, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parents[1]
NT = {'gradius_nes': 'Gradius', 'gradius2_fc': 'Gradius II', 'lifeforce_nes': 'Life Force', 'salamander_fc': 'Salamander FC'}
MT = {'nemesis': 'Nemesis', 'nemesis2': 'Nemesis 2', 'salamander': 'Salamander', 'nemesis3': 'Nemesis 3'}

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--evidence', type=pathlib.Path, required=True)
    a = ap.parse_args()
    L = json.loads((a.evidence / 'music_match/music_match.json').read_text())
    rows = []
    for e in L:
        cands = sorted(e.get('candidates') or [], key=lambda c: -(c.get('similarity') or 0))
        rows.append(dict(msx_game=e['msx_game'], msx_code=e['msx_code'], msx_name=e.get('msx_name'), kind=e.get('msx_kind'),
                         decision=e.get('decision') or 'SILENT_SLOT', chosen=e.get('chosen'),
                         best_candidates=[dict(nes_game=c.get('nes_game'), nes_code=c.get('nes_code'), nes_title=c.get('nes_title'),
                                               similarity=c.get('similarity'), verdict=c.get('verdict'))
                                          for c in cands if c.get('verdict') in ('same', 'arrangement')][:4],
                         notes=e.get('notes') or ''))
    counts = {}
    for g in MT:
        rs = [r for r in rows if r['msx_game'] == g]
        counts[g] = dict(codes=len(rs), **collections.Counter(r['decision'] for r in rs))
    src = collections.Counter(NT.get((r['chosen'] or {}).get('nes_game'), '?') for r in rows if r['decision'] == 'USE_NES')
    out = dict(schema=1, generated=datetime.date.today().isoformat(), rule='docs/DECISIONS.md, Music', counts=counts,
               chosen_from=dict(src.most_common()), entries=rows)
    (ROOT / 'manifests/music_choice.json').write_text(json.dumps(out, indent=1, ensure_ascii=False) + '\n')
    M = ['# Music choice, MSX vs NES (Phase 2c) - generated by tools/music_choice.py; do not edit', '',
         'For every MSX music and jingle: the same composition in the NES games, found by comparing the notes',
         'each game\'s own sound driver plays (transposition-invariant), and the decision. USE_NES = Legends uses',
         'the NES version (the most complete arrangement when several NES games have it; Gradius II on a tie;',
         'Life Force and Salamander FC play bit-identical tunes, Salamander FC is named). CONVERT_MSX = no NES',
         'version: converted later in two arrangements (plain APU and MMC5). SILENT_SLOT = an empty music slot.', '',
         '| game | codes | use NES | convert | silent |', '|---|---|---|---|---|']
    for g, c in counts.items():
        M.append('| %s | %d | %d | %d | %d |' % (MT[g], c['codes'], c.get('USE_NES', 0), c.get('CONVERT_MSX', 0), c.get('SILENT_SLOT', 0)))
    M += ['', 'NES sources chosen: ' + ', '.join('%s %d' % kv for kv in src.most_common()) + '.']
    for g in MT:
        M += ['', '## %s' % MT[g], '', '| code | name | kind | decision | NES version | best similarity |', '|---|---|---|---|---|---|']
        for r in [r for r in rows if r['msx_game'] == g]:
            ch = r['chosen'] or {}
            nes = '%s %s %s' % (NT.get(ch.get('nes_game'), ''), ch.get('nes_code') or '', ch.get('nes_title') or '') if ch else '-'
            best = r['best_candidates'][0] if r['best_candidates'] else None
            bs = '%s %s (%.2f)' % (NT.get(best['nes_game'], best['nes_game']), best['nes_code'], best['similarity'] or 0) if best else '-'
            M.append('| %s | %s | %s | %s | %s | %s |' % (r['msx_code'], (r['msx_name'] or '').replace('|', '/'), r['kind'], r['decision'], nes.strip() or '-', bs))
    (ROOT / 'docs/MUSIC_CHOICE.md').write_text('\n'.join(M) + '\n')
    print(json.dumps(counts), dict(src))
    return 0

if __name__ == '__main__':
    sys.exit(main())
